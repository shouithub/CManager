def _parse_po(path):
    """Parse .po into entries preserving source order."""
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    entries = []
    current = None
    pending_comments = []
    for line in lines:
        if line.startswith("msgid "):
            if current is not None:
                entries.append(current)
            current = {"raw": [], "msgid": None, "msgstr": None, "msgstr_line": None}
            # 把位于 msgid 之前的注释（#, fuzzy / #| 旧 msgid 参考行等）
            # 归入本条目，而不是挂在上一条目上。
            if pending_comments:
                current["raw"].extend(pending_comments)
                pending_comments = []
        if current is None:
            if line.startswith("#"):
                pending_comments.append(line)
            continue
        stripped = line.strip()
        if stripped.startswith("#") and current["msgstr_line"] is not None:
            # msgstr 之后的注释属于下一条目
            pending_comments.append(line)
            continue
        current["raw"].append(line)
        if stripped.startswith('msgid "'):
            current["msgid"] = stripped[len('msgid "'):-1].replace('\\"', '"')
        elif current["msgid"] is not None and stripped.startswith('"') and current["msgstr"] is None:
            current["msgid"] += stripped[1:-1].replace('\\"', '"')
        elif stripped.startswith('msgstr "'):
            current["msgstr"] = stripped[len('msgstr "'):-1].replace('\\"', '"')
            current["msgstr_line"] = len(current["raw"]) - 1
        elif current["msgstr"] is not None and stripped.startswith('"'):
            current["msgstr"] += stripped[1:-1].replace('\\"', '"')
    if current is not None:
        entries.append(current)
    return entries


def _escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def fill_po(path, language_index):
    entries = _parse_po(path)
    filled = 0
    saw_header = False
    kept = []
    for entry in entries:
        if not entry["msgid"]:
            if not saw_header:
                saw_header = True
                kept.append(entry)
            # Drop non-header entries with an empty msgid: they are duplicates
            # of the header entry and make msgfmt fail.  They carry no
            # translatable content (empty verbose_name/help_text).
            continue
        if entry["msgid"] is None or entry["msgstr_line"] is None:
            kept.append(entry)
            continue
        translation = CATALOG.get(entry["msgid"])
        if not translation:
            kept.append(entry)
            continue
        # CATALOG 是权威翻译源：对已知词条始终覆盖 msgstr（包括 makemessages
        # 生成的 fuzzy 占位译文和旧译文），并清除 fuzzy 标记与旧 msgid 参考行，
        # 避免 msgfmt 把它们当未翻译处理。
        entry["raw"] = [
            line for line in entry["raw"][:entry["msgstr_line"]]
            if not (line.strip().startswith('#,') and 'fuzzy' in line)
            and not line.strip().startswith('#|')
        ]
        entry["raw"].append(f'msgstr "{_escape(translation[language_index])}"\n')
        filled += 1
        kept.append(entry)
    path.write_text("".join(raw for entry in kept for raw in entry["raw"]), encoding="utf-8")
    print(f"Filled {filled} entries in {path}")


